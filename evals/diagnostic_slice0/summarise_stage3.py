"""Writes results/stage3_summary.md from the Stage 3 adversarial before/after runs (offline, reads JSON only)."""

from __future__ import annotations

import collections
import json
from pathlib import Path

RES = Path(__file__).resolve().parent / "results"
before = {r["case"]: r for r in json.loads((RES / "stage3_adversarial_before.json").read_text())}
after = {r["case"]: r for r in json.loads((RES / "stage3_adversarial_after.json").read_text())}


def tally(rows, kind=None):
    return dict(sorted(collections.Counter(r["outcome"] for r in rows if kind in (None, r["kind"])).items()))


lines = ["# Stage 3 adversarial summary (synthetic; generated by summarise_stage3.py)", "",
         "Before = same questions with the calculation dropped (generated cases: the production path as it was; engine cases: "
         "the Stage 1/2 reference gate as a stand-in). After = verifier on. The `malicious` category has no before: the old "
         "system had no formula channel.", ""]
for kind in ("generated", "engine"):
    lines += [f"## {kind}", "", f"- before: {tally(before.values(), kind)}", f"- after:  {tally(after.values(), kind)}", ""]
common = [c for c in after if c in before]
def pick(rule, kind):
    return [c for c in common if after[c]["kind"] == kind and rule(before[c]["outcome"], after[c]["outcome"])]


BLOCKED = ("TRUE_REJECT", "SAFE_BLOCK", "BLOCKED_OTHER", "INCONCLUSIVE_OK", "KNOWN_LIMIT_BLOCKED")
lines += ["## Changes (engine rows use the old reference gate as a stand-in for before; generated rows are the real production path)", ""]
for kind in ("generated", "engine"):
    missed = pick(lambda b, a: b == "FALSE_ACCEPT" and a in BLOCKED, kind)
    rescued = pick(lambda b, a: b == "FALSE_REJECT" and a == "TRUE_ACCEPT", kind)
    regress = pick(lambda b, a: b == "TRUE_ACCEPT" and a != "TRUE_ACCEPT", kind)
    lines += [f"### {kind}", "",
              f"- previously missed quantitative errors now blocked ({len(missed)}): {', '.join(missed) or 'none'}", "",
              f"- correct derived answers previously rejected, now verified ({len(rescued)}): {', '.join(rescued) or 'none'}", "",
              f"- previously accepted correctly, no longer accepted ({len(regress)}): {', '.join(regress) or 'none'}", ""]
fa = [c for c, r in after.items() if r["outcome"] in ("FALSE_ACCEPT", "KNOWN_LIMIT_FALSE_ACCEPT")]
fr = [c for c, r in after.items() if r["outcome"] == "FALSE_REJECT"]
lines += ["### after, all rows", "",
          f"- false accepts ({len(fa)}, every one a documented known limit): {', '.join(fa) or 'none'}", "",
          f"- false rejects ({len(fr)}): {', '.join(fr) or 'none'}", "",
          f"- safe blocks (wrong, blocked only as INCONCLUSIVE): "
          f"{', '.join(c for c, r in after.items() if r['outcome'] == 'SAFE_BLOCK') or 'none'}", "",
          f"- unverified valid (correct but INCONCLUSIVE): "
          f"{', '.join(c for c, r in after.items() if r['outcome'] == 'UNVERIFIED_VALID') or 'none'}", ""]
by_cat = collections.defaultdict(collections.Counter)
for r in after.values():
    by_cat[r["category"]][r["outcome"]] += 1
lines += ["## After, by category", ""] + [f"- {c}: {dict(sorted(v.items()))}" for c, v in sorted(by_cat.items())]
(RES / "stage3_summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
